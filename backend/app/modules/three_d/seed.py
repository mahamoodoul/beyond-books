"""Seed the platform 3D library with the schematic demo heart (idempotent).

python -m app.modules.three_d.seed
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.database.session import session_factory
from app.integrations.storage import get_storage
from app.modules.three_d.assets_service import GLB_MIME, register_version_bytes
from app.modules.three_d.demo_heart import build_heart_glb
from app.modules.three_d.models import (
    AssetVisibility,
    ReviewStatus,
    ThreeDAsset,
    ThreeDAssetVersion,
)

DEMO_HEART_SLUG = "demo_heart_schematic"


def seed_demo_heart(db: Session) -> ThreeDAsset:
    asset = db.scalar(select(ThreeDAsset).where(ThreeDAsset.slug == DEMO_HEART_SLUG))
    if asset is not None:
        return asset
    asset = ThreeDAsset(
        slug=DEMO_HEART_SLUG,
        visibility=AssetVisibility.LIBRARY,
        name="Heart (schematic demo)",
        description="Simplified four-chamber heart built from ellipsoids for development and "
        "demos. NOT anatomically accurate — replace with a medically reviewed model.",
        category="anatomy",
        subject="biology",
        license_name="CC0-1.0",
        attribution_text="Generated by the Edu3D project (schematic placeholder).",
        provider="seed",
    )
    db.add(asset)
    db.flush()
    data = build_heart_glb()
    v = ThreeDAssetVersion(
        asset_id=asset.id,
        version_number=1,
        file_size_bytes=len(data),
        storage_key=f"assets/{asset.id}/v1/model.glb",
    )
    db.add(v)
    get_storage().put_bytes(v.storage_key, data, GLB_MIME)
    register_version_bytes(asset, v, data)
    asset.review_status = ReviewStatus.APPROVED
    asset.review_notes = "Seeded placeholder; schematic only."
    db.commit()
    return asset


if __name__ == "__main__":
    s = session_factory()()
    try:
        a = seed_demo_heart(s)
        print(f"seeded {a.slug} (v{a.latest_version}, {a.review_status})")
    finally:
        s.close()
